#!/usr/bin/env python3
"""Prometheus metrics and redacted JSON event logs for one Docker Compose project.

Uses the Docker read-only API through a restricted socket proxy. Never exports
Docker Config.Env, mounts, network details, inspect JSON, or request payloads.
"""
import collections
import datetime as dt
import json
import os
import threading
import time
import urllib.error
import urllib.parse
import urllib.request

import scrape_metrics
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path

API = os.environ.get("DOCKER_HOST_HTTP", "http://docker-socket-proxy:2375").rstrip("/")
PROJECT = os.environ.get("DDD_PROJECT", "ddd-platform")
PERIOD = max(5, int(os.environ.get("POLL_SECONDS", "10")))
EVENT_LOG = Path("/state/history/events.jsonl")
STATE_FILE = Path("/state/state.env")
lock = threading.Lock()
last_metrics = 'ddd_observer_scrape_success 0\n'
last_states = {}
OTLP = os.environ.get("OTEL_METRICS_ENDPOINT", "http://lgtm:4318/v1/metrics")
POSTGRES_EXPORTER = os.environ.get("POSTGRES_EXPORTER_URL", "http://postgres-exporter:9187/metrics")
REDIS_EXPORTER = os.environ.get("REDIS_EXPORTER_URL", "http://redis-exporter:9121/metrics")
previous_cpu = {}
read_lines = 0


def docker_get(route):
    req = urllib.request.Request(API + route, headers={"Accept": "application/json"})
    with urllib.request.urlopen(req, timeout=7) as response:
        return json.loads(response.read())


def escaped(value):
    return str(value or "").replace("\\", "\\\\").replace("\n", "\\n").replace('"', '\\"')


def metric(name, value, labels=None):
    if labels:
        lbl = ','.join(f'{k}="{escaped(v)}"' for k, v in sorted(labels.items()))
        return f'{name}{{{lbl}}} {value}\n'
    return f'{name} {value}\n'


def event(**fields):
    print(json.dumps(fields, separators=(",", ":"), ensure_ascii=True), flush=True)


def epoch(value):
    if not value or value.startswith('0001-'):
        return 0
    try:
        return dt.datetime.fromisoformat(value.replace('Z', '+00:00')).timestamp()
    except ValueError:
        return 0


def desired_replicas():
    try:
        lines = STATE_FILE.read_text(encoding='utf-8').splitlines()
        for line in lines:
            if line.startswith('APP_REPLICAS='):
                return max(1, min(50, int(line.split('=', 1)[1])))
    except (OSError, ValueError):
        pass
    return 3


def fetch_containers():
    filters = urllib.parse.quote(json.dumps({"label": [f"com.docker.compose.project={PROJECT}"]}))
    summaries = docker_get(f'/containers/json?all=1&filters={filters}')
    return [docker_get('/containers/' + urllib.parse.quote(c['Id'], safe='') + '/json')
            for c in summaries]


def image_match(ref, actual_id):
    if not ref or not actual_id:
        return -1
    try:
        image = docker_get('/images/' + urllib.parse.quote(ref, safe='') + '/json')
        return int(image.get('Id') == actual_id)
    except (urllib.error.HTTPError, urllib.error.URLError, ValueError):
        return -1


def check_deployment_events():
    global read_lines
    try:
        with EVENT_LOG.open(encoding='utf-8') as source:
            lines = source.readlines()
    except FileNotFoundError:
        return
    if len(lines) < read_lines:
        read_lines = 0
    # On a cold start, emit only the last 30 records, not an unbounded replay.
    start = max(read_lines, len(lines) - 30) if read_lines == 0 else read_lines
    for line in lines[start:]:
        try:
            record = json.loads(line)
            event(event='deployment', **record)
        except (ValueError, TypeError):
            pass
    read_lines = len(lines)



def export_otlp_metrics(lines):
    """Push observer gauges through the LGTM OTLP receiver (JSON encoding).

    Keep names stable for the existing Grafana dashboards. No raw Docker inspect
    document, environment variable, token, or request body is exported.
    """
    import re
    now = str(time.time_ns())
    metrics = []
    pattern = re.compile(r'^(\w+)(?:\{(.*)\})? (-?\d+(?:\.\d+)?)$')
    for line in lines:
        match = pattern.match(line.strip())
        if not match:
            continue
        name, encoded_labels, value = match.groups()
        attributes = []
        if encoded_labels:
            # Labels generated by metric() escape commas and quotes.
            label_pattern = re.compile(r'(\w+)="((?:\\.|[^"\\])*)"(?:,|$)')
            for label in label_pattern.finditer(encoded_labels):
                attributes.append({"key": label.group(1),
                                   "value": {"stringValue": label.group(2)}})
        metrics.append({"name": name, "gauge": {"dataPoints": [{
            "timeUnixNano": now, "asDouble": float(value), "attributes": attributes
        }]}})
    if not metrics:
        return
    document = {"resourceMetrics": [{
        "resource": {"attributes": [{"key": "service.name",
                                    "value": {"stringValue": "ddd-ops-observer"}}]},
        "scopeMetrics": [{"scope": {"name": "ddd.docker"}, "metrics": metrics}]
    }]}
    body = json.dumps(document, separators=(",", ":")).encode("utf-8")
    request = urllib.request.Request(OTLP, data=body, method="POST",
                                     headers={"Content-Type": "application/json"})
    try:
        with urllib.request.urlopen(request, timeout=6) as response:
            response.read()
    except (urllib.error.URLError, TimeoutError) as exc:
        event(event="otel_metric_export_failed", error_type=type(exc).__name__)

def container_stats(cid):
    """Docker stats over read-only API; no secrets or raw inspect data exported."""
    global previous_cpu
    try:
        info = docker_get('/containers/' + urllib.parse.quote(cid, safe='') + '/stats?stream=false')
        mem = info.get('memory_stats') or {}
        cpu = info.get('cpu_stats') or {}
        total = ((cpu.get('cpu_usage') or {}).get('total_usage') or 0)
        system = cpu.get('system_cpu_usage') or 0
        cores = cpu.get('online_cpus') or len((cpu.get('cpu_usage') or {}).get('percpu_usage') or []) or 1
        current = (total, system)
        old = previous_cpu.get(cid)
        previous_cpu[cid] = current
        if old and system > old[1] and total >= old[0]:
            percent = (total - old[0]) / (system - old[1]) * cores * 100
        else:
            percent = 0
        return int(mem.get('usage') or 0), int(mem.get('limit') or 0), percent
    except (ValueError, KeyError, urllib.error.URLError, TimeoutError):
        return None


def scrape_targets(items):
    targets = [
        {'job': 'postgres', 'service': 'postgres', 'instance': 'postgres-exporter',
         'url': POSTGRES_EXPORTER},
        {'job': 'redis', 'service': 'redis', 'instance': 'redis-exporter',
         'url': REDIS_EXPORTER},
    ]
    for item in items:
        labels = ((item.get('Config') or {}).get('Labels') or {})
        service = labels.get('com.docker.compose.service')
        if service not in ('modular-app', 'gateway', 'eureka'):
            continue
        if not (item.get('State') or {}).get('Running'):
            continue
        networks = ((item.get('NetworkSettings') or {}).get('Networks') or {})
        # Docker Compose project prefix is dynamic, but network suffix is stable.
        ips = [network.get('IPAddress') for key, network in networks.items()
               if key.endswith('_application') and network.get('IPAddress')]
        if not ips:
            continue
        port = 8761 if service == 'eureka' else 8080
        targets.append({
            'job': 'spring-actuator', 'service': service,
            'instance': str(item.get('Id') or '')[:12],
            'container': str(item.get('Name') or '').lstrip('/'),
            'url': f'http://{ips[0]}:{port}/actuator/prometheus',
        })
    return targets


def refresh():
    global last_metrics, last_states
    items = fetch_containers()
    stats = collections.defaultdict(lambda: {'running': 0, 'healthy': 0})
    lines = [metric('ddd_observer_scrape_success', 1)]
    current_states = {}
    for item in items:
        config = item.get('Config') or {}
        lbl = config.get('Labels') or {}
        service = lbl.get('com.docker.compose.service', '')
        if not service:
            continue
        cid = str(item.get('Id', ''))[:12]
        name = str(item.get('Name', '')).lstrip('/')[:100]
        state = item.get('State') or {}
        running = int(bool(state.get('Running')))
        health = (state.get('Health') or {}).get('Status', 'none')
        restart_count = int(item.get('RestartCount') or 0)
        ref = str(config.get('Image', ''))[:160]
        sha = str(item.get('Image', ''))
        labels = {'service': service, 'container': name, 'container_id': cid}
        info_labels = {
            **labels,
            'image_ref': ref,
            'image_sha': sha[:19],
            'release': str(lbl.get('org.opencontainers.image.version', ''))[:90],
            'revision': str(lbl.get('org.opencontainers.image.revision', ''))[:60],
        }
        if running:
            load = container_stats(str(item.get('Id') or ''))
            if load is not None:
                usage, limit, cpu_percent = load
                lines.extend([
                    metric('ddd_container_memory_usage_bytes', usage, labels),
                    metric('ddd_container_memory_limit_bytes', limit, labels),
                    metric('ddd_container_cpu_percent', cpu_percent, labels),
                ])
        stats[service]['running'] += running
        stats[service]['healthy'] += int(health == 'healthy' and running == 1)
        lines += [
            metric('ddd_container_info', 1, info_labels),
            metric('ddd_container_running', running, labels),
            metric('ddd_container_restart_count', restart_count, labels),
            metric('ddd_container_health', 1, {**labels, 'health': health}),
            metric('ddd_container_started_at_seconds', epoch(state.get('StartedAt')), labels),
            metric('ddd_container_created_at_seconds', epoch(item.get('Created', '')), labels),
            metric('ddd_container_image_drift', image_match(ref, sha), labels),
        ]
        fingerprint = (str(state.get('Status')), health, restart_count, sha)
        current_states[cid] = fingerprint
        if last_states.get(cid) != fingerprint:
            event(event='container_state', container_id=cid, container=name, service=service,
                  state=state.get('Status'), health=health, restarts=restart_count,
                  image_ref=ref, image_sha=sha[:19], started_at=state.get('StartedAt'))
    for cid in set(last_states) - set(current_states):
        event(event='container_removed', container_id=cid)
    last_states = current_states

    services = {'modular-app', 'gateway', 'eureka', 'nginx', 'postgres', 'redis'} | set(stats)
    desired = desired_replicas()
    for service in sorted(services):
        lines.extend([
            metric('ddd_service_replicas_running', stats[service]['running'], {'service': service}),
            metric('ddd_service_replicas_healthy', stats[service]['healthy'], {'service': service}),
            metric('ddd_service_replicas_desired', desired if service == 'modular-app' else 1, {'service': service}),
        ])
    with lock:
        last_metrics = ''.join(lines)
    export_otlp_metrics(lines)
    scrape_metrics.export(
        url=None, endpoint=OTLP, targets=scrape_targets(items),
        on_error=lambda job, error: event(event='metrics_scrape_error', job=job, error_type=error),
    )


class Handler(BaseHTTPRequestHandler):
    def do_GET(self):
        if self.path not in ('/metrics', '/health'):
            self.send_error(404)
            return
        if self.path == '/health':
            payload = b'ok\n'
            content_type = 'text/plain'
        else:
            with lock:
                payload = last_metrics.encode('utf-8')
            content_type = 'text/plain; version=0.0.4; charset=utf-8'
        self.send_response(200)
        self.send_header('Content-Type', content_type)
        self.send_header('Content-Length', str(len(payload)))
        self.end_headers()
        self.wfile.write(payload)

    def log_message(self, *_):
        pass


def poll():
    global last_metrics
    while True:
        try:
            check_deployment_events()
            refresh()
        except Exception as ex:
            # Don't output URL query or HTTP response bodies.
            event(event='observer_error', error_type=type(ex).__name__)
            with lock:
                last_metrics = metric('ddd_observer_scrape_success', 0)
        time.sleep(PERIOD)


if __name__ == '__main__':
    threading.Thread(target=poll, daemon=True).start()
    ThreadingHTTPServer(('0.0.0.0', 9209), Handler).serve_forever()
